def cmd_summary(_: argparse.Namespace) -> int:
    table = load_table()
    crates = table["crate"]
    by_kind: dict[str, int] = {}
    by_layer: dict[int, int] = {}
    by_phase: dict[str, int] = {}
    nested = sum(1 for c in crates if c.get("parent"))
    for c in crates:
        by_kind[c["kind"]] = by_kind.get(c["kind"], 0) + 1
        by_layer[c["layer"]] = by_layer.get(c["layer"], 0) + 1
        by_phase[c["phase"]] = by_phase.get(c["phase"], 0) + 1
    top = sum(1 for c in crates if c["path"].startswith("crates/") and not c.get("parent"))
    print(f"packages={len(crates)} top-level-crates={top} nested={nested} external-deps={len(table['ext'])}")
    print("kinds:", dict(sorted(by_kind.items())))
    print("layers:", dict(sorted(by_layer.items())))
    print("phases:", dict(sorted(by_phase.items())))
    return 0


