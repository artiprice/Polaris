#!/usr/bin/env python3
"""Polaris workspace tooling — driven by @prime/tools/workspace.toml.

Run with the isolated interpreter from the repository root:

    python -I @prime/tools/workspace.py <command>

Commands
    gen                 Regenerate the root Cargo.toml and every skeleton package
                        (apps/*, crates/*, crates/*/crates/*, tests, tests/spike/*, xtask).
                        Only files carrying the @generated marker are ever deleted.
    check-members       Every workspace glob match has a Cargo.toml, no stray files sit at
                        glob level, and the matched set equals the crate table.
    check-layers        `cargo metadata` edges equal the table edges and obey the layer rule.
    audit-versions      Every external dependency exists on the crates.io sparse index, is not
                        yanked, and declares rust_version <= workspace rust-version; git deps
                        resolve to the pinned rev.
    probe               Write @prime/tools/dep-probe (standalone workspace with every external
                        dependency at its pinned version/features) and run `cargo generate-lockfile`.
    chatlog-inventory   Mechanically extract directives, commands, mentions, crate names, Rust
                        types/functions and model names from @prime/chatlog.json; with --check FILE,
                        fail if any item is absent from FILE.
    summary             Print package counts per kind/layer/phase.
    phase-tables        Print per-phase crate task tables (--kind phases) or status rows (--kind status)
                        for @prime/PHASES.md / @prime/PHASES_STATUS.md.
    check-docs          Every package has a PLAN.md module section, a PHASES.md task and a
                        PHASES_STATUS.md row; every spike S0-1..S0-13 appears in all three documents.

Exit status is 0 on success and 1 on any failed check.
"""

