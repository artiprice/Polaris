def cmd_phase_tables(args: argparse.Namespace) -> int:
    """Print per-phase crate task tables (PHASES.md) or status rows (PHASES_STATUS.md)."""
    table = load_table()
    by_name = crates_by_name(table)
    if args.kind == "setup":
        print("<!-- generated: member setup (workspace.toml [[member_setup]]) -->")
        print("| Id | Where | Component | Version (verified) | Install | From | Required |")
        print("|---|---|---|---|---|---|---|")
        for s in table.get("member_setup", []):
            req = "**yes**" if s["required"] else "optional"
            print(f"| `{s['id']}` | {s['where']} | {s['component']} | {s['version']} | {s['install']} | {s['from']} | {req} |")
        print()
        return 0
    for phase in PHASE_ORDER:
        crates = [c for c in table["crate"] if c["phase"] == phase]
        if not crates:
            continue
        print(f"<!-- generated: {phase} crate tasks -->")
        if args.kind == "phases":
            print("| Task | Crate | Layer | Depends on (crate tasks) | Exit criteria | Per-PC setup (§0.1) |")
            print("|---|---|---|---|---|---|")
            for c in crates:
                deps = ", ".join(f"`{crate_task_id(d)}`" for d in c.get("deps", [])) or "—"
                if c["kind"] == "facade":
                    exit_c = "re-exports compile; children's tasks PASS"
                elif c["kind"] in ("app",):
                    exit_c = "real `main`; smoke test PASS; PLAN §13 TODO done"
                elif c["kind"] == "spike":
                    exit_c = "burst scenarios run; pass criteria met with evidence"
                else:
                    exit_c = "PLAN §13 TODO done; descriptors' tests PASS; no unwrap/panic paths"
                setup = ", ".join(f"`{i}`" for i in c.get("member_setup", [])) or "—"
                print(f"| `{crate_task_id(c['name'])}` | `{c['name']}` | L{c['layer']} | {deps} | {exit_c} | {setup} |")
        else:
            print("| Task | Crate | Phase | Status | Evidence |")
            print("|---|---|---|---|---|")
            for c in crates:
                status = c.get("status", "NOT STARTED")
                evidence = c.get("evidence", "doc-only skeleton (see P0-SKEL-6)")
                print(f"| `{crate_task_id(c['name'])}` | `{c['name']}` | {phase} | {status} | {evidence} |")
        print()
