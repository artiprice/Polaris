//! Generates the Slint `Tokens` global from the shared design tokens, then compiles the UI.
//!
//! Colours are never copied into `.slint` files by hand (PLAN §polaris-ui-gui TODO): every role of
//! `polaris_ui_model::tokens::ROLES` and of `src/palette.rs` becomes an `out property <color>`.

use std::fmt::Write as _;
use std::path::PathBuf;

use polaris_ui_model::tokens::{ColorRole, FONTS, RADIUS_PX, ROLES, SPEED_MS};

#[path = "src/palette.rs"]
mod palette;

fn push_roles(out: &mut String, roles: &[ColorRole]) -> Result<(), std::fmt::Error> {
    for role in roles {
        writeln!(out, "    // {}", role.source)?;
        writeln!(out, "    out property <color> {}: {};", role.name, role.hex)?;
    }
    Ok(())
}

fn tokens_slint() -> Result<String, std::fmt::Error> {
    let mut out = String::from(
        "// @generated by polaris-ui-gui/build.rs from polaris_ui_model::tokens and src/palette.rs.\n\
         export global Tokens {\n",
    );
    push_roles(&mut out, ROLES)?;
    push_roles(&mut out, palette::WELCOME_ROLES)?;
    writeln!(out, "    out property <length> radius: {RADIUS_PX}px;")?;
    writeln!(out, "    out property <duration> speed: {SPEED_MS}ms;")?;
    for (suffix, family) in FONTS {
        writeln!(
            out,
            "    out property <string> font-{suffix}: \"{family}\";"
        )?;
    }
    out.push_str("}\n");
    Ok(out)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed=src/palette.rs");
    println!("cargo:rerun-if-changed=ui");
    println!("cargo:rerun-if-changed=assets");
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").ok_or("OUT_DIR is not set")?);
    let generated = out_dir.join("slint-tokens");
    std::fs::create_dir_all(&generated)?;
    std::fs::write(generated.join("tokens.slint"), tokens_slint()?)?;
    let config = slint_build::CompilerConfiguration::new()
        .with_include_paths(vec![generated])
        .embed_resources(slint_build::EmbedResourcesKind::EmbedFiles)
        // Element debug info lets the headless tests find elements by accessible label.
        .with_debug_info(std::env::var("PROFILE").is_ok_and(|profile| profile == "debug"));
    slint_build::compile_with_config("ui/app.slint", config)?;
    Ok(())
}
